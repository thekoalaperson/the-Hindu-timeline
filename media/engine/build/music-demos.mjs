#!/usr/bin/env node
// Renders short audition wavs for every node of the music hierarchy into
// engine/demos/ so BASE / RAGA / RAGAxMOOD choices are auditable by ear
// (see engine/CONTRACTS.md "Music hierarchy").
//
//   node engine/build/music-demos.mjs
//
// Files (16-bit 44.1k stereo, ~20.5 MB total):
//   base-drone.wav        8s  BASE: tanpura pa-SA-SA-sa cycle only
//   <raga>.wav           12s  RAGA: drone + one characteristic phrase,
//                             looped, no percussion
//   <raga>-<mood>.wav    12s  RAGA x MOOD: full texture (drone, tala,
//                             generative melody + cadence, envelope,
//                             stereo width) for the six pairs that matter
// Also writes engine/demos/README.md (what to listen for, per file).
//
// Everything is synthesized through music.mjs's exported primitives — no
// duplicated DSP. Deterministic: the shared rng is reset per file.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { engineDir } from './lib.mjs';
import {
  NOTE, RAGAS, MOOD,
  pluck, flute,
  initBuffers, resetRng, setEnv, writeWav, composeMood,
} from './music.mjs';

const outDir = join(engineDir, 'demos');
mkdirSync(outDir, { recursive: true });

const TANPURA = [NOTE.A2, NOTE.D3, NOTE.D3, NOTE.D2];
function droneUntil(tEnd, gain = 0.16) {
  let t = 0.2, k = 0;
  while (t < tEnd) {
    pluck(t, TANPURA[k % 4], gain, 3.6, -0.25);
    t += 0.78; k++;
  }
}

function render(file, seconds, fn) {
  initBuffers(seconds);
  resetRng();
  fn();
  const { dur, peak, norm } = writeWav(join(outDir, file));
  console.log(`  ${file.padEnd(26)} ${dur}s  peak ${peak.toFixed(3)}  norm ${norm.toFixed(3)}`);
}

// ── BASE: drone only ──
render('base-drone.wav', 8, () => {
  droneUntil(6.8);
  setEnv([[0, 0], [0.8, 0.85], [6.5, 0.85], [7.7, 0.06], [8, 0]]);
});

// ── RAGA: drone + characteristic phrase loop, no percussion ──
// Hand-picked audition phrases, each ending in the raga's cadence figure.
const PHRASES = {
  yamanish: [['D4', 0.6], ['Fs4', 0.6], ['A4', 0.7], ['B4', 1.2], ['Cs5', 0.6], ['D5', 1.4]],   // ascent skip, rest on B, Cs->D resolve
  bhairavish: [['Bb4', 0.9], ['A4', 0.9], ['F4', 1.0], ['Eb4', 1.1], ['D4', 1.5]],              // grave komal descent to D
  deshish: [['E4', 0.6], ['G4', 0.7], ['A4', 0.8], ['B4', 0.7], ['A4', 0.7], ['D5', 1.4]],      // lyrical, B->A->D cadence
};
function phraseSpan(ph) {
  let s = 0;
  for (let i = 0; i < ph.length - 1; i++) s += Math.max(0.5, ph[i][1] * 0.7);
  return s + ph[ph.length - 1][1] + 0.4;
}
for (const raga of Object.keys(RAGAS)) {
  render(`${raga}.wav`, 12, () => {
    droneUntil(10.2);
    const ph = PHRASES[raga], span = phraseSpan(ph);
    let t = 0.9;
    while (t + span <= 11.2) {
      let nt = t;
      for (let i = 0; i < ph.length; i++) {
        flute(nt, ph[i][0], ph[i][1], i === ph.length - 1 ? 0.32 : 0.28);
        nt += Math.max(0.5, ph[i][1] * 0.7);
      }
      t += span + 0.9;
    }
    setEnv([[0, 0], [0.8, 0.8], [10.3, 0.8], [11.7, 0.05], [12, 0]]);
  });
}

// ── RAGA x MOOD: full texture via the real mood composer ──
const PAIRS = [
  ['yamanish', 'festive'], ['yamanish', 'triumphant'],
  ['bhairavish', 'somber'], ['bhairavish', 'suspense'],
  ['deshish', 'tender'], ['deshish', 'tense'],
];
for (const [raga, mood] of PAIRS) {
  render(`${raga}-${mood}.wav`, 12, () => {
    const TL = { total: 11, scenes: [{ id: `demo-${raga}-${mood}`, start: 0, end: 11, mood }] };
    composeMood(TL, { music: { raga } }, { quiet: true });
  });
}

// ── listening notes ──
writeFileSync(join(outDir, 'README.md'), `# Music hierarchy demos

Generated by \`node engine/build/music-demos.mjs\` (deterministic — safe to
regenerate). Each file auditions one node of the BASE -> RAGA -> MOOD
hierarchy in \`engine/build/music.mjs\`.

| file | listen for |
|---|---|
| base-drone.wav | BASE alone: the tanpura pa-SA-SA-sa cycle (A2 D3 D3 D2), even and hypnotic — every score sits on this. |
| yamanish.wav | Bright ascent with skips, a long rest on B, then the leading-tone Cs5 resolving up to D5. |
| bhairavish.wav | Grave komal color (Bb, F, Eb) sinking stepwise to a low D — no brightness anywhere. |
| deshish.wav | Lyrical natural-C flavor rising through G and A, closing with the gentle B -> A -> D cadence. |
| yamanish-festive.wav | Full tala at 1.7 beats/s under fast high-register phrases; the widest, most sparkling texture. |
| yamanish-triumphant.wav | Heavier drums (1.75 beats/s, hardest gain), full drone, high phrases resting on B — the loudest mix. |
| bhairavish-somber.wav | No percussion, sparse long low notes, narrow stereo — the darkest, slowest texture. |
| bhairavish-suspense.wav | Thin drone, quiet sparse taps, short low komal fragments with lots of air between them. |
| deshish-tender.wav | No percussion, warm mid-register phrases with long sustains, medium width. |
| deshish-tense.wav | Fast sparse taps (1.9 beats/s) under clipped low phrases — tension from texture while the raga stays sweet. |

Mood affinity when a story pins nothing: festive/triumphant -> yamanish,
somber/mystic/suspense/tense -> bhairavish, tender -> deshish. Override with
story.json \`music.raga\`, per scene with script.json \`scene.raga\`, or
\`--raga\` on music.mjs / film.mjs audio.
`);
console.log(`wrote ${join(outDir, 'README.md')}`);
